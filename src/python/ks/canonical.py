"""Canonical KS cotangent lift and fixed-energy regularization.

Conventions
-----------
The spinor phase space uses canonical coordinates ``(q, Q)`` in
``T*R^4``.  The Hopf/KS position map is

``x = (2(q1 q3 + q2 q4), 2(q1 q4 - q2 q3),
       q1^2 + q2^2 - q3^2 - q4^2)``.

It satisfies ``|x| = |q|^2 = r``.  Physical canonical momentum is

``p = DKS(q) Q / (4 r)``.

The factor four is essential: on the zero momentum-map level it gives
``Q . dq = p . dx`` and the standard physical Poisson brackets.  Some
references use a momentum twice as large; that chart has brackets scaled by
two and is not the convention used here.

The simultaneous circle rotation of both coordinate pairs has momentum map

``Xi = q1 Q2 - q2 Q1 + q3 Q4 - q4 Q3``.

At ``Xi = 0`` the map descends to the six-dimensional Kepler phase space.
For Kepler energy ``h < 0``, reduced mass ``m > 0``, and potential strength
``kappa > 0``, the
Sundman Hamiltonian

``K = r (H_kepler - h) = |Q|^2 / (8 m) - kappa - h |q|^2``

generates the physical Kepler flow with ``dt/ds = r`` on ``K = 0``.  It is a
regular isotropic harmonic oscillator, including at ``q = 0``.

References
----------
J. C. van der Meer, "Reduction and regularization of the Kepler problem",
Celestial Mechanics and Dynamical Astronomy 133, 32 (2021).
Lei Zhao, "Kustaanheimo-Stiefel Regularization and the Quadrupolar
Conjugacy", arXiv:1308.2314 (2013).
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Iterable

import numpy as np
from numpy.typing import ArrayLike, NDArray


FloatArray = NDArray[np.float64]
_DIM_SPINOR = 4
_DIM_PHYSICAL = 3


def _vector(value: ArrayLike, size: int, name: str) -> FloatArray:
    array = np.asarray(value, dtype=float)
    if array.shape != (size,):
        raise ValueError(f"{name} must have shape ({size},), got {array.shape}")
    if not np.all(np.isfinite(array)):
        raise ValueError(f"{name} must contain only finite values")
    result = array.copy()
    result.setflags(write=False)
    return result


@dataclass(frozen=True)
class KSPhaseState:
    """Canonical spinor position and momentum in ``T*R^4``."""

    q: FloatArray
    Q: FloatArray

    def __post_init__(self) -> None:
        object.__setattr__(self, "q", _vector(self.q, _DIM_SPINOR, "q"))
        object.__setattr__(self, "Q", _vector(self.Q, _DIM_SPINOR, "Q"))

    @property
    def radius(self) -> float:
        return float(np.dot(self.q, self.q))

    @property
    def xi(self) -> float:
        return momentum_map(self.q, self.Q)

    def as_vector(self) -> FloatArray:
        return np.concatenate((self.q, self.Q))


@dataclass(frozen=True)
class KeplerPhaseState:
    """Physical Cartesian position and canonical momentum in ``T*R^3``."""

    x: FloatArray
    p: FloatArray

    def __post_init__(self) -> None:
        object.__setattr__(self, "x", _vector(self.x, _DIM_PHYSICAL, "x"))
        object.__setattr__(self, "p", _vector(self.p, _DIM_PHYSICAL, "p"))
        if np.linalg.norm(self.x) == 0.0:
            raise ValueError("physical Kepler state is undefined at x = 0")

    @property
    def radius(self) -> float:
        return float(np.linalg.norm(self.x))

    def as_vector(self) -> FloatArray:
        return np.concatenate((self.x, self.p))


def ks_position(q: ArrayLike) -> FloatArray:
    """Map a four-dimensional spinor position to physical ``R^3``."""
    q1, q2, q3, q4 = _vector(q, _DIM_SPINOR, "q")
    return np.array(
        [
            2.0 * (q1 * q3 + q2 * q4),
            2.0 * (q1 * q4 - q2 * q3),
            q1 * q1 + q2 * q2 - q3 * q3 - q4 * q4,
        ]
    )


def ks_jacobian(q: ArrayLike) -> FloatArray:
    """Return the ``3 x 4`` Jacobian of :func:`ks_position`."""
    q1, q2, q3, q4 = _vector(q, _DIM_SPINOR, "q")
    return 2.0 * np.array(
        [
            [q3, q4, q1, q2],
            [q4, -q3, -q2, q1],
            [q1, q2, -q3, -q4],
        ]
    )


def fiber_generator(q: ArrayLike) -> FloatArray:
    """Infinitesimal generator of the simultaneous ``S1`` phase action."""
    q1, q2, q3, q4 = _vector(q, _DIM_SPINOR, "q")
    return np.array([-q2, q1, -q4, q3])


def momentum_map(q: ArrayLike, Q: ArrayLike) -> float:
    """Evaluate the circle-action momentum map ``Xi(q, Q)``."""
    q_array = _vector(q, _DIM_SPINOR, "q")
    Q_array = _vector(Q, _DIM_SPINOR, "Q")
    return float(np.dot(fiber_generator(q_array), Q_array))


def _rotation(angle: float) -> FloatArray:
    cosine = np.cos(angle)
    sine = np.sin(angle)
    return np.array([[cosine, -sine], [sine, cosine]])


def s1_action(state: KSPhaseState, angle: float) -> KSPhaseState:
    """Apply the Hamiltonian ``S1`` action generated by ``Xi``."""
    if not np.isfinite(angle):
        raise ValueError("angle must be finite")
    rotation = _rotation(float(angle))
    q = np.concatenate((rotation @ state.q[:2], rotation @ state.q[2:]))
    Q = np.concatenate((rotation @ state.Q[:2], rotation @ state.Q[2:]))
    return KSPhaseState(q=q, Q=Q)


def project_cotangent(
    state: KSPhaseState,
    *,
    require_zero_level: bool = True,
    level_tolerance: float = 1e-12,
) -> KeplerPhaseState:
    """Project a KS state to canonical physical position and momentum.

    The zero-level requirement is the Marsden-Weinstein reduction used by the
    ordinary Kepler problem.  Projection at nonzero level is algebraically
    defined but carries a magnetic term and is therefore opt-in.
    """
    radius = state.radius
    if radius == 0.0:
        raise ValueError("cotangent projection is undefined at q = 0")
    if level_tolerance < 0.0:
        raise ValueError("level_tolerance must be non-negative")
    if require_zero_level and abs(state.xi) > level_tolerance:
        raise ValueError(
            f"KS state is not on Xi = 0: |Xi|={abs(state.xi):.3e}"
        )
    x = ks_position(state.q)
    p = ks_jacobian(state.q) @ state.Q / (4.0 * radius)
    return KeplerPhaseState(x=x, p=p)


def _position_lift(x: FloatArray) -> FloatArray:
    radius = float(np.linalg.norm(x))
    if radius == 0.0:
        raise ValueError("KS position lift is undefined at x = 0")

    north_scale = radius + x[2]
    south_scale = radius - x[2]
    if north_scale >= south_scale:
        q1 = np.sqrt(max(0.0, north_scale / 2.0))
        if q1 == 0.0:
            raise ArithmeticError("north KS chart is singular")
        return np.array([q1, 0.0, x[0] / (2.0 * q1), x[1] / (2.0 * q1)])

    q3 = np.sqrt(max(0.0, south_scale / 2.0))
    if q3 == 0.0:
        raise ArithmeticError("south KS chart is singular")
    return np.array([x[0] / (2.0 * q3), -x[1] / (2.0 * q3), q3, 0.0])


def lift_cotangent(
    state: KeplerPhaseState,
    *,
    angle: float = 0.0,
    momentum_level: float = 0.0,
) -> KSPhaseState:
    """Lift a physical state into a selected KS gauge.

    ``momentum_level`` adds the vertical momentum required for a specified
    value of ``Xi``.  The ordinary Kepler lift uses the default zero level.
    """
    if not np.isfinite(angle):
        raise ValueError("angle must be finite")
    if not np.isfinite(momentum_level):
        raise ValueError("momentum_level must be finite")

    q = _position_lift(state.x)
    Q_horizontal = ks_jacobian(q).T @ state.p
    generator = fiber_generator(q)
    Q = Q_horizontal + (float(momentum_level) / state.radius) * generator
    lifted = KSPhaseState(q=q, Q=Q)
    if angle != 0.0:
        lifted = s1_action(lifted, angle)
    return lifted


@dataclass(frozen=True)
class ZeroMomentumQuotient:
    """Operational representation of ``Xi^-1(0) / S1``.

    The quotient chart is the canonical Kepler phase state.  ``section``
    chooses one local Hopf gauge, while ``reduce`` is constant on the complete
    circle orbit.  The section is not global at collision, as expected; the
    regularized oscillator itself remains defined there.
    """

    level_tolerance: float = 1e-12

    def __post_init__(self) -> None:
        if not np.isfinite(self.level_tolerance) or self.level_tolerance < 0.0:
            raise ValueError("level_tolerance must be finite and non-negative")

    def reduce(self, state: KSPhaseState) -> KeplerPhaseState:
        """Map a zero-level KS state to its quotient representative."""
        return project_cotangent(
            state,
            require_zero_level=True,
            level_tolerance=self.level_tolerance,
        )

    def section(self, state: KeplerPhaseState, *, angle: float = 0.0) -> KSPhaseState:
        """Choose a local zero-level representative of a quotient state."""
        return lift_cotangent(state, angle=angle, momentum_level=0.0)

    def equivalent(
        self,
        first: KSPhaseState,
        second: KSPhaseState,
        *,
        tolerance: float = 1e-11,
    ) -> bool:
        """Return whether two zero-level states represent one quotient point."""
        if tolerance < 0.0 or not np.isfinite(tolerance):
            raise ValueError("tolerance must be finite and non-negative")
        first_reduced = self.reduce(first).as_vector()
        second_reduced = self.reduce(second).as_vector()
        return bool(np.allclose(first_reduced, second_reduced, atol=tolerance, rtol=0.0))


def canonical_poisson_matrix(dimension: int) -> FloatArray:
    """Return the canonical Poisson tensor for ``(q, p)`` ordering."""
    if dimension <= 0:
        raise ValueError("dimension must be positive")
    identity = np.eye(dimension)
    zero = np.zeros_like(identity)
    return np.block([[zero, identity], [-identity, zero]])


def cotangent_projection_jacobian(state: KSPhaseState) -> FloatArray:
    """Analytic Jacobian of ``(q,Q) -> (x,p)`` away from collision."""
    radius = state.radius
    if radius == 0.0:
        raise ValueError("projection Jacobian is undefined at q = 0")

    position_jacobian = ks_jacobian(state.q)
    physical = project_cotangent(state, require_zero_level=False)
    dp_dq = (
        ks_jacobian(state.Q) / (4.0 * radius)
        - 2.0 * np.outer(physical.p, state.q) / radius
    )
    dp_dQ = position_jacobian / (4.0 * radius)
    return np.block(
        [
            [position_jacobian, np.zeros((_DIM_PHYSICAL, _DIM_SPINOR))],
            [dp_dq, dp_dQ],
        ]
    )


def projected_poisson_matrix(state: KSPhaseState) -> FloatArray:
    """Push the canonical KS Poisson tensor through the cotangent map."""
    derivative = cotangent_projection_jacobian(state)
    return derivative @ canonical_poisson_matrix(_DIM_SPINOR) @ derivative.T


@dataclass(frozen=True)
class NegativeEnergyKSSystem:
    """Fixed-negative-energy Kepler system in regularized KS variables."""

    kappa: float
    energy: float
    reduced_mass: float = 1.0

    def __post_init__(self) -> None:
        if not np.isfinite(self.kappa) or self.kappa <= 0.0:
            raise ValueError("kappa must be finite and positive")
        if not np.isfinite(self.energy) or self.energy >= 0.0:
            raise ValueError("energy must be finite and negative")
        if not np.isfinite(self.reduced_mass) or self.reduced_mass <= 0.0:
            raise ValueError("reduced_mass must be finite and positive")

    @property
    def gravitational_parameter(self) -> float:
        """Return ``kappa / reduced_mass`` for the relative acceleration."""
        return float(self.kappa / self.reduced_mass)

    @property
    def angular_frequency(self) -> float:
        return float(np.sqrt(-self.energy / (2.0 * self.reduced_mass)))

    def kepler_hamiltonian(self, state: KeplerPhaseState) -> float:
        return float(
            np.dot(state.p, state.p) / (2.0 * self.reduced_mass)
            - self.kappa / state.radius
        )

    def regularized_hamiltonian(self, state: KSPhaseState) -> float:
        return float(
            np.dot(state.Q, state.Q) / (8.0 * self.reduced_mass)
            - self.kappa
            - self.energy * state.radius
        )

    def validate_shell(self, state: KSPhaseState, tolerance: float = 1e-12) -> bool:
        """Return whether ``state`` lies on ``K = 0`` and ``Xi = 0``."""
        if tolerance < 0.0:
            raise ValueError("tolerance must be non-negative")
        return (
            abs(self.regularized_hamiltonian(state)) <= tolerance
            and abs(state.xi) <= tolerance
        )

    def vector_field(self, state: KSPhaseState) -> tuple[FloatArray, FloatArray]:
        """Return ``(dq/ds, dQ/ds)`` for the regular oscillator."""
        return state.Q / (4.0 * self.reduced_mass), 2.0 * self.energy * state.q

    def flow(self, state: KSPhaseState, s: ArrayLike) -> tuple[FloatArray, FloatArray]:
        """Evaluate the exact regular harmonic-oscillator flow.

        Returns arrays with final dimension four.  A scalar ``s`` therefore
        returns two vectors of shape ``(4,)``.
        """
        s_array = np.asarray(s, dtype=float)
        if not np.all(np.isfinite(s_array)):
            raise ValueError("s must contain only finite values")
        omega = self.angular_frequency
        phase = omega * s_array
        cosine = np.cos(phase)[..., np.newaxis]
        sine = np.sin(phase)[..., np.newaxis]
        mass_frequency = self.reduced_mass * omega
        q = state.q * cosine + state.Q * sine / (4.0 * mass_frequency)
        Q = state.Q * cosine - 4.0 * mass_frequency * state.q * sine
        return q, Q

    def physical_time(self, state: KSPhaseState, s: ArrayLike) -> FloatArray:
        """Integrate ``dt/ds = |q(s)|^2`` analytically from ``s = 0``."""
        s_array = np.asarray(s, dtype=float)
        if not np.all(np.isfinite(s_array)):
            raise ValueError("s must contain only finite values")
        omega = self.angular_frequency
        a = state.q
        b = state.Q / (4.0 * self.reduced_mass * omega)
        aa = float(np.dot(a, a))
        bb = float(np.dot(b, b))
        ab = float(np.dot(a, b))
        double_phase = 2.0 * omega * s_array
        return (
            0.5 * (aa + bb) * s_array
            + (aa - bb) * np.sin(double_phase) / (4.0 * omega)
            + ab * (1.0 - np.cos(double_phase)) / (2.0 * omega)
        )

    def quotient_period(self) -> float:
        """Return the fictitious-time period after quotienting by ``S1``."""
        return float(np.pi / self.angular_frequency)

    def physical_period(self, state: KSPhaseState) -> float:
        """Return elapsed physical time over one quotient orbit."""
        return float(self.physical_time(state, self.quotient_period()))

    def trajectory(
        self, state: KSPhaseState, s: Iterable[float]
    ) -> tuple[FloatArray, FloatArray, FloatArray]:
        """Return physical times, positions, and momenta along exact KS flow."""
        s_array = np.asarray(tuple(s), dtype=float)
        q, Q = self.flow(state, s_array)
        times = self.physical_time(state, s_array)
        positions = np.empty((s_array.size, _DIM_PHYSICAL))
        momenta = np.empty_like(positions)
        for index in range(s_array.size):
            physical = project_cotangent(KSPhaseState(q[index], Q[index]))
            positions[index] = physical.x
            momenta[index] = physical.p
        return times, positions, momenta
